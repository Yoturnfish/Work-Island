using WorkIsland.App;
using WorkIsland.Core;

internal static partial class Program
{
    private static async Task RunPointerSnapshotLive(IslandWindow island,string output,Action<string,bool,object?> check)
    {
        const BindingFlags statics=BindingFlags.Static|BindingFlags.NonPublic;
        var type=typeof(WindowsActivity);var pointer=type.GetField("pointerAt",statics)!;var keyboard=type.GetField("keyboardAt",statics)!;
        var location=type.GetField("lastPointerPosition",statics)!;var packet=type.GetField("inputPacket",statics)!;
        nint Effective()=>(nint)type.GetProperty("EffectiveWindow",statics)!.GetValue(null)!;
        nint UnderRecordedPoint()
        {
            var point=location.GetValue(null);if(point is null)return 0;
            var hit=type.GetMethod("WindowFromPoint",statics)!.Invoke(null,[point]);
            return (nint)type.GetMethod("GetAncestor",statics)!.Invoke(null,[hit,2u])!;
        }
        FieldInfo Timer(string name)=>typeof(IslandWindow).GetField(name,Flags)!;
        ((DispatcherTimer)Timer("fullscreenTimer").GetValue(island)!).Stop();((DispatcherTimer)Timer("timer").GetValue(island)!).Stop();island.Hide();
        var area=SystemParameters.WorkArea;var left=area.Left+(area.Width-390)/2;var top=area.Top+220;
        var button=new Button{Content="点击一次，验证下次采样的窗口",Margin=new Thickness(25),Height=75};var clicks=0;button.Click+=(_,_)=>clicks++;
        var below=new Window{Title="Work Island · 指针后层",Width=390,Height=210,Left=left,Top=top,ShowActivated=false,ShowInTaskbar=true,Content=new TextBlock{Text="采样时应识别这个窗口",Margin=new Thickness(25)}};
        var above=new Window{Title="Work Island · 指针采样验收",Width=390,Height=210,Left=left,Top=top,ShowActivated=false,ShowInTaskbar=true,Topmost=true,Content=button};
        below.Show();above.Show();var a=new WindowInteropHelper(above).Handle;var b=new WindowInteropHelper(below).Handle;
        var events=0;var input=(HwndSource)type.GetField("inputSource",statics)!.GetValue(null)!;
        HwndSourceHook hook=(nint hwnd,int message,nint w,nint l,ref bool handled)=>{if(message==0xff)events++;return 0;};input.AddHook(hook);
        var observations=new List<object>();var watch=Stopwatch.StartNew();
        File.WriteAllText(Path.Combine(output,"input-ready.json"),JsonSerializer.Serialize(new{processId=Environment.ProcessId,windowHandle=a.ToInt64(),belowHandle=b.ToInt64(),title=above.Title,scope="Official one click on own button. Then fixture moves its own window before evaluating production EffectiveWindow. No cursor movement or input generated by fixture."},AtomicStore.JsonOptions));
        try
        {
            while(clicks==0&&watch.Elapsed.TotalSeconds<180)await Task.Delay(25);
            check("official actual pointer click reached the owned window",clicks==1,new{clicks,events});if(clicks==0)return;
            await Task.Delay(80);var at=(long?)pointer.GetValue(null);var k=(long)keyboard.GetValue(null)!;var before=UnderRecordedPoint();
            check("latest real raw input selects pointer at the front fixture",at is not null&&at>=k&&before==a,new{at,k,before=before.ToInt64(),expected=a.ToInt64()});
            var rawBeforeMove=events;above.Left=area.Left+15;await Task.Delay(100);
            var after=UnderRecordedPoint();var unchanged=Equals(pointer.GetValue(null),at)&&events==rawBeforeMove;
            check("owned window changes before evaluation without another raw input",unchanged&&after==b,new{unchanged,events,rawBeforeMove,after=after.ToInt64(),expected=b.ToInt64()});
            var effective=Effective();check("production evaluation resolves pointer window at snapshot time",effective==b,new{actual=effective.ToInt64(),expected=b.ToInt64()});
            observations.Add(new{phase="moved-before-evaluation",actual=effective.ToInt64(),expected=b.ToInt64(),unchanged});
            above.Left=left;await Task.Delay(100);var underneath=UnderRecordedPoint();var cached=Effective();
            check("without new pointer input a second evaluation retains Mac cached result",Equals(pointer.GetValue(null),at)&&underneath==a&&cached==b,new{actual=cached.ToInt64(),expectedCached=b.ToInt64(),underneath=underneath.ToInt64()});
            check("raw packet buffer remains cleared after pointer evaluation",Array.TrueForAll((byte[])packet.GetValue(null)!,x=>x==0),null);
            observations.Add(new{phase="no-new-input",actual=cached.ToInt64(),expected=b.ToInt64(),currentUnderPointer=underneath.ToInt64()});
        }
        finally
        {
            input.RemoveHook(hook);above.Close();below.Close();
            File.WriteAllText(Path.Combine(output,"pointer-snapshot.json"),JsonSerializer.Serialize(new{processId=Environment.ProcessId,clicks,events,observations,scope="Official real mouse click and production WM_INPUT adapter. Two own WPF windows moved by fixture around recorded pointer point; production EffectiveWindow evaluated afterward. Same process, so proves HWND selection, not cross-application/browser URL or physical hardware."},AtomicStore.JsonOptions));
        }
    }
}
